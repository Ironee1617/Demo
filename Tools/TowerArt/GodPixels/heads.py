def beard(c, name, mats=None):
    for x0, y0, rows in BEARDS[name]:
        draw(c, rows, x0, y0, mats=mats, ring='outer')


def gear(c, name, stage='front', mats=None, dy=0):
    for layer in HEADGEAR[name]:
        x0, y0, rows = layer[:3]
        opts = layer[3] if len(layer) > 3 else {}
        if opts.get('stage', 'front') != stage:
            continue
        m = dict(opts.get('mats') or {})
        if mats:
            m.update(mats)
        draw(c, rows, x0, y0 + dy, mats=m, ring=opts.get('ring', 'all'), ring_mat=opts.get('ring_mat'))
